#!/usr/bin/env bash
# Compile the Rust core to WebAssembly and place it where the interface loads it.
# Needs a Rust toolchain with the wasm32-unknown-unknown target.
set -euo pipefail
cd "$(dirname "$0")/../core"
cargo build --release --target wasm32-unknown-unknown --target-dir target-wasm
WASM=target-wasm/wasm32-unknown-unknown/release/ankhwiz_core.wasm
ls -l "$WASM"
# The interface carries the module as text, so every build (including a
# single file opened from disk, where fetching a .wasm is not allowed) loads it the same way.
{
  echo '// Generated by scripts/build-core.sh from the Rust core. Do not edit.'
  printf 'export const CORE_WASM_BASE64 =\n  "'
  base64 -w0 "$WASM"
  printf '";\n'
} > ../src/lib/core/wasm.generated.ts
